"""Hotkeys are compositor bindings that run `cronjovi run <slug>`.

Wayland has no portable global hotkeys, so each compositor gets an adapter:
sync writes a generated file next to its config, and a single line in the
user's config (added by `sync --link-hotkeys`, removed on uninstall) loads it.
"""

import json
import os
import re
import shutil
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from . import paths
from .workflow import Workflow, WorkflowError

MARKER = "cronjovi (managed by install.sh)"
DESCRIPTION = "Cron Jovi"
MODIFIERS = {"super": "SUPER", "mod": "SUPER", "shift": "SHIFT", "ctrl": "CTRL",
             "control": "CTRL", "alt": "ALT"}
MODMASK = {"SHIFT": 1, "CTRL": 4, "ALT": 8, "SUPER": 64}


def parse(hotkey: str) -> tuple[list[str], str]:
    parts = [part.strip() for part in hotkey.split("+")]
    *mods, key = parts
    unknown = [mod for mod in mods if mod.lower() not in MODIFIERS]
    if unknown or not re.fullmatch(r"\w+", key):
        raise WorkflowError(f"bad hotkey '{hotkey}'")
    return [MODIFIERS[mod.lower()] for mod in mods], key


def same(first: str, second: str) -> bool:
    """Whether two hotkeys are the same keys, however they're written."""
    mods_a, key_a = parse(first)
    mods_b, key_b = parse(second)
    return sorted(mods_a) == sorted(mods_b) and key_a.upper() == key_b.upper()


def command(slug: str) -> list[str]:
    installed = None if os.environ.get("APPIMAGE") else shutil.which("cronjovi")
    if installed:
        return [installed, "run", slug]
    return [*paths.self_command(), "run", slug]


def _lua_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def hyprland_lua(workflows: list[Workflow]) -> str:
    lines = ["-- Generated by `cronjovi sync`. Edits here are overwritten."]
    for wf in workflows:
        mods, key = parse(wf.trigger.hotkey)
        keys = " + ".join([*mods, key.upper() if len(key) == 1 else key])
        label = f"{DESCRIPTION}: {wf.name}"
        # hl.bind rather than Omarchy's o.bind, so this works on stock Hyprland too.
        lines.append(
            f"hl.bind({_lua_string(keys)}, hl.dsp.exec_cmd({_lua_string(' '.join(command(wf.slug)))}), "
            f"{{ description = {_lua_string(label)} }})"
        )
    return "\n".join(lines) + "\n"


def hyprland_conf(workflows: list[Workflow]) -> str:
    lines = ["# Generated by `cronjovi sync`. Edits here are overwritten."]
    for wf in workflows:
        mods, key = parse(wf.trigger.hotkey)
        lines.append(f"bind = {' '.join(mods)}, {key}, exec, {' '.join(command(wf.slug))}")
    return "\n".join(lines) + "\n"


def niri_kdl(workflows: list[Workflow]) -> str:
    lines = ["// Generated by `cronjovi sync`. Edits here are overwritten.", "binds {"]
    for wf in workflows:
        mods, key = parse(wf.trigger.hotkey)
        names = [mod.capitalize() for mod in mods]
        chord = "+".join([*names, key])
        spawn = " ".join(json.dumps(arg) for arg in command(wf.slug))
        lines.append(f'    {chord} {{ spawn {spawn}; }}')
    lines.append("}")
    return "\n".join(lines) + "\n"


@dataclass
class Adapter:
    name: str
    config: Path  # the user's main config
    generated: Path
    render: Callable[[list[Workflow]], str]
    link_line: str
    after: str = ""  # insert the link line after this line, if present

    def available(self) -> bool:
        return self.config.exists()

    def linked(self) -> bool:
        return MARKER in self.config.read_text()


def adapters() -> list[Adapter]:
    hypr = paths.config_home() / "hypr"
    niri = paths.config_home() / "niri"
    return [
        Adapter(
            "hyprland", hypr / "hyprland.lua", hypr / "cronjovi.lua", hyprland_lua,
            f'pcall(require, "hypr.cronjovi") -- {MARKER}',
            after='require("hypr.bindings")',
        ),
        Adapter(
            "hyprland", hypr / "hyprland.conf", hypr / "cronjovi.conf", hyprland_conf,
            f"source = {hypr / 'cronjovi.conf'} # {MARKER}",
        ),
        Adapter(
            "niri", niri / "config.kdl", niri / "cronjovi.kdl", niri_kdl,
            f'include "cronjovi.kdl" // {MARKER}',
        ),
    ]


def active() -> list[Adapter]:
    found = [adapter for adapter in adapters() if adapter.available()]
    # Omarchy's Lua config replaces hyprland.conf; never serve both.
    if any(a.config.name == "hyprland.lua" for a in found):
        found = [a for a in found if a.config.name != "hyprland.conf"]
    return found


def link(adapter: Adapter) -> None:
    if adapter.linked():
        return
    text = adapter.config.read_text()
    backup = adapter.config.with_name(f"{adapter.config.name}.bak.{int(time.time())}")
    shutil.copy2(adapter.config, backup)
    lines = text.splitlines()
    if adapter.after in lines:
        lines.insert(lines.index(adapter.after) + 1, adapter.link_line)
    else:
        lines.append(adapter.link_line)
    adapter.config.write_text("\n".join(lines) + "\n")


def unlink(adapter: Adapter) -> None:
    if adapter.available() and adapter.linked():
        lines = [ln for ln in adapter.config.read_text().splitlines() if MARKER not in ln]
        adapter.config.write_text("\n".join(lines) + "\n")
    adapter.generated.unlink(missing_ok=True)


def hyprland_conflicts(workflows: list[Workflow]) -> list[str]:
    """Hotkeys already taken by another binding on the running Hyprland."""
    if not os.environ.get("HYPRLAND_INSTANCE_SIGNATURE"):
        return []
    proc = subprocess.run(["hyprctl", "binds", "-j"], capture_output=True, text=True)
    if proc.returncode:
        return []
    taken = {}
    for bind in json.loads(proc.stdout):
        if not bind.get("description", "").startswith(DESCRIPTION):
            taken[(bind["modmask"], bind["key"].upper())] = bind.get("description") or "another bind"
    conflicts = []
    for wf in workflows:
        mods, key = parse(wf.trigger.hotkey)
        mask = sum(MODMASK[mod] for mod in mods)
        if (mask, key.upper()) in taken:
            conflicts.append(
                f"{wf.trigger.hotkey} ({wf.name}) is also bound to: {taken[(mask, key.upper())]}"
            )
    return conflicts


def reload_hyprland() -> str:
    if not os.environ.get("HYPRLAND_INSTANCE_SIGNATURE"):
        return ""
    subprocess.run(["hyprctl", "reload"], capture_output=True)
    errors = subprocess.run(["hyprctl", "configerrors"], capture_output=True, text=True).stdout
    errors = errors.strip()
    return "" if not errors or errors.lower().startswith("no errors") else errors


def sync_hotkeys(workflows: list[Workflow], link_config: bool = False) -> list[str]:
    """Write bindings for each compositor. Returns messages for the user."""
    bound = [w for w in workflows if w.enabled and w.trigger.hotkey]
    messages = []
    for adapter in active():
        changed = False
        text = adapter.render(bound)
        if not adapter.generated.exists() or adapter.generated.read_text() != text:
            adapter.generated.write_text(text)
            changed = True
        if link_config and not adapter.linked():
            link(adapter)
            changed = True
        if not adapter.linked():
            messages.append(
                f"{adapter.name}: {adapter.generated} is not loaded yet; run "
                "`cronjovi sync --link-hotkeys` to add it to your config"
            )
        elif changed and adapter.name == "hyprland":
            errors = reload_hyprland()
            if errors:
                messages.append(f"hyprland config errors:\n{errors}")
        if adapter.name == "hyprland":
            messages += hyprland_conflicts(bound)
    return messages


def remove_all() -> None:
    for adapter in adapters():
        unlink(adapter)
    if os.environ.get("HYPRLAND_INSTANCE_SIGNATURE"):
        reload_hyprland()
